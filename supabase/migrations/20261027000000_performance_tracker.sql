-- DXP+ performance tracker schema (Supabase project: dxp-performance-tracker)
-- Mirrors what is live in the database. Run on a fresh project to recreate it.

-- Clean data the dashboard reads: one row per site per month
create table if not exists public.performance_data (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  year        smallint not null check (year between 2020 and 2100),
  month       smallint not null check (month between 1 and 12),
  region      text not null check (region in ('Europe', 'APAC', 'Americas')),
  market      text not null,
  brand       text not null,
  site        text not null,
  uptime_pct  numeric(6,3) check (uptime_pct between 0 and 100),
  apdex       numeric(4,3) check (apdex between 0 and 1),
  lcp_s       numeric(6,2) check (lcp_s >= 0),
  inp_ms      integer      check (inp_ms >= 0),
  cls         numeric(5,3) check (cls >= 0),
  ttfb_ms     integer      check (ttfb_ms >= 0),
  sessions    integer      check (sessions >= 0),
  constraint performance_data_site_month_key unique (site, year, month)
);

alter table public.performance_data enable row level security;
create policy "read performance data" on public.performance_data
  for select to anon, authenticated using (true);

-- Read a number written with a comma or a dot: 99,84 / 99.84 / 1.234,5 / 1,234.5
create or replace function public.parse_num(v text)
returns numeric language plpgsql immutable set search_path = '' as $$
declare s text; pc int; pd int;
begin
  if v is null then return null; end if;
  s := regexp_replace(trim(v), '[[:space:]%]|ms$|s$', '', 'gi');
  if s = '' then return null; end if;
  pc := position(',' in reverse(s));
  pd := position('.' in reverse(s));
  if pc > 0 and pd > 0 then                      -- both used: the last one is the decimal
    if pc < pd then s := replace(replace(s, '.', ''), ',', '.');
    else s := replace(s, ',', ''); end if;
  elsif pc > 0 then                              -- only commas
    if length(s) - length(replace(s, ',', '')) > 1 then s := replace(s, ',', '');
    else s := replace(s, ',', '.'); end if;
  elsif length(s) - length(replace(s, '.', '')) > 1 then
    s := replace(s, '.', '');                    -- 1.234.567
  end if;
  return s::numeric;
exception when others then
  raise exception 'Could not read "%" as a number', v;
end $$;

-- Whole numbers: 34.931 or 34,931 = 34931; anything else is rounded
create or replace function public.parse_int(v text)
returns integer language plpgsql immutable set search_path = '' as $$
begin
  if v is null or trim(v) = '' then return null; end if;
  if trim(v) ~ '^-?\d{1,3}([.,]\d{3})+$' then
    return replace(replace(trim(v), '.', ''), ',', '')::integer;
  end if;
  return round(public.parse_num(v))::integer;
end $$;

-- Import table: every column is text, so CSVs with "," or "." decimals are accepted
create table if not exists public.performance_import (
  id         bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  year text, month text, region text, market text, brand text, site text,
  uptime_pct text, apdex text, lcp_s text, inp_ms text, cls text, ttfb_ms text, sessions text
);
alter table public.performance_import enable row level security;  -- no policies: not readable by the dashboard

-- Each imported row is converted and upserted into performance_data
create or replace function public.apply_performance_import()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.performance_data
    (year, month, region, market, brand, site, uptime_pct, apdex, lcp_s, inp_ms, cls, ttfb_ms, sessions)
  values (
    public.parse_int(new.year), public.parse_int(new.month),
    trim(new.region), trim(new.market), trim(new.brand), trim(new.site),
    public.parse_num(new.uptime_pct), public.parse_num(new.apdex), public.parse_num(new.lcp_s),
    public.parse_int(new.inp_ms), public.parse_num(new.cls), public.parse_int(new.ttfb_ms),
    public.parse_int(new.sessions))
  on conflict (site, year, month) do update set
    region = excluded.region, market = excluded.market, brand = excluded.brand,
    uptime_pct = excluded.uptime_pct, apdex = excluded.apdex, lcp_s = excluded.lcp_s,
    inp_ms = excluded.inp_ms, cls = excluded.cls, ttfb_ms = excluded.ttfb_ms,
    sessions = excluded.sessions;
  return new;
end $$;

drop trigger if exists performance_import_apply on public.performance_import;
create trigger performance_import_apply
  after insert on public.performance_import
  for each row execute function public.apply_performance_import();
